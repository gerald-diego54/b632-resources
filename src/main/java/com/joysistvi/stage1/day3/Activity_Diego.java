package com.joysistvi.stage1.day3;

public class Activity_Diego {

    static void main(String[] args) {

        // Boolean: stores either true or false
        boolean isStudent = true;

        // Byte: stores small whole numbers
        byte age = 25;

        // Short: stores whole numbers larger than byte
        short year = 2026;

        // Integer: stores whole numbers
        int score = 98;

        // Long: stores very large whole numbers
        long population = 1217638726138L;

        // Float: stores decimal numbers with less precision
        float temperature = 37.5f;

        // Double: stores decimal numbers with higher precision
        double price = 199.95;

        // Character: stores a single character
        char grade = 'A';

        // String: stores a sequence of characters or text
        String name = "Gerald A. Diego";


        // Prints the value of the boolean variable
        System.out.println("Boolean: " + isStudent);

        // Prints the value of the byte variable
        System.out.println("Byte: " + age);

        // Prints the value of the short variable
        System.out.println("Short: " + year);

        // Prints the value of the integer variable
        System.out.println("Integer: " + score);

        // Prints the value of the long variable
        System.out.println("Long: " + population);

        // Prints the value of the float variable
        System.out.println("Float: " + temperature);

        // Prints the value of the double variable
        System.out.println("Double: " + price);

        // Prints the value of the character variable
        System.out.println("Character: " + grade);

        // Prints the value of the String variable
        System.out.println("String: " + name);
    }
}
